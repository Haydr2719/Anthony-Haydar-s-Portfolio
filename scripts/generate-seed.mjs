// Generates supabase/migrations/03_content.sql from src/content/fallback.ts.
// Usage: npm run seed:generate   (Node 22.18+ / 23.6+ for built-in TypeScript stripping)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as content from "../src/content/fallback.ts";

const JSONB_COLUMNS = new Set(["faqs", "schedule"]);

function literal(column, value) {
  if (value === null || value === undefined) return "null";
  if (JSONB_COLUMNS.has(column)) return `${quote(JSON.stringify(value))}::jsonb`;
  if (Array.isArray(value)) {
    return value.length ? `array[${value.map(quote).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  return quote(String(value));
}

function quote(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

function inserts(table, rows) {
  if (!rows.length) return `-- ${table}: no rows\n`;
  return (
    rows
      .map((row) => {
        const cols = Object.keys(row).filter((k) => row[k] !== undefined);
        const values = cols.map((c) => literal(c, row[c]));
        return `insert into public.${table} (${cols.join(", ")})\nvalues (${values.join(", ")})\non conflict do nothing;`;
      })
      .join("\n\n") + "\n"
  );
}

const sections = [
  ["site_settings", [content.fallbackSettings]],
  ["pages", content.fallbackPages],
  ["content_blocks", content.fallbackBlocks],
  ["services", content.fallbackServices],
  ["projects", content.fallbackProjects],
  ["drinks", content.fallbackDrinks],
  ["programs", content.fallbackPrograms],
  ["events", content.fallbackEvents],
  ["experience", content.fallbackExperience],
  ["testimonials", content.fallbackTestimonials],
  ["partners", content.fallbackPartners],
  ["media_items", content.fallbackMedia],
  ["banners", content.fallbackBanners],
];

const header = `-- =============================================================================
-- Anthony Haydar Website - 03 Starting content
-- STEP 3 of 4. Run after 02_security.sql.
--
-- Real content only (from the brief and Anthony's CV) - no sample data:
--   site settings & contact details, page SEO, all page text, the 4 consultancy
--   services, career & credentials, and client projects (Sira and Cherry on top
--   as drafts until the clients approve; 9 consulting projects published).
--   Drinks, workshops, events, media, testimonials and partners start empty -
--   add them in /admin.
--
-- GENERATED by "npm run seed:generate" from src/content/fallback.ts - do not edit by hand.
-- Uses "on conflict do nothing", so re-running it never overwrites content
-- edited in the admin.
-- =============================================================================

`;

const body = sections.map(([table, rows]) => `-- ${table}\n${inserts(table, rows)}`).join("\n");
const out = fileURLToPath(new URL("../supabase/migrations/03_content.sql", import.meta.url));
writeFileSync(out, header + body);
console.log(`Wrote ${out}`);
